#!/usr/bin/env python3
"""Generates the data store gate's driver, into the gate's scratch directory.

    python3 test/gate/state-assert-drive-gen.py <out.pd> <state dir>

Two synthetic contributors. u_state's contract is that a `manual` answer is
synchronous: Pd is depth-first, so every honest answer is stored by the time the
save broadcast returns. One contributor answers at once and one from behind a
[del 5], and the gate asserts the late one is absent from the file.

Every delay hangs off one loadbang with an absolute time, so no wait is the sum
of the ones before it.
"""
import sys

# No defaults: the old ones wrote the driver into the repo and shared one state
# directory across every run.
if len(sys.argv) < 3:
    sys.exit("usage: state-assert-drive-gen.py <out.pd> <state dir>")
OUT, DIR = sys.argv[1], sys.argv[2]

B, C = [], []


def obj(x, y, s):
    B.append("#X obj %d %d %s;" % (x, y, s))
    return len(B) - 1


def msg(x, y, s):
    B.append("#X msg %d %d %s;" % (x, y, s))
    return len(B) - 1


def txt(x, y, s, f=70):
    B.append("#X text %d %d %s, f %d;" % (x, y, s, f))
    return len(B) - 1


def con(a, ao, b, bi):
    C.append("#X connect %d %d %d %d;" % (a, ao, b, bi))


txt(20, 20, "GENERATED by state-assert-drive-gen.py -- DO NOT HAND-EDIT. "
    "Regenerated by state-assert.py into its scratch directory on every run.")

lb = obj(20, 140, "loadbang")
st = obj(20, 1500, "u_state %s" % DIR)

txt(1500, 140, "The honest contributor answers the save broadcast in the same "
    "call stack \\, as every real one must.")
rs = obj(1500, 320, "r state")
ro = obj(1500, 380, "route save restore")
good = msg(1500, 450, "put manual take-1 kick 36 snare 38")
gs = obj(1500, 500, "s state")
pr = obj(1900, 450, "print RESTORE")
con(rs, 0, ro, 0)
con(ro, 0, good, 0)
con(good, 0, gs, 0)
con(ro, 1, pr, 0)

txt(2250, 140, "The dishonest one answers 5 ms late and must not reach the "
    "file: if this key appears \\, the synchronous contract no longer holds.")
bd = obj(2250, 380, "del 5")
bm = msg(2250, 450, "put manual late-key 999")
bs = obj(2250, 500, "s state")
con(ro, 0, bd, 0)
con(bd, 0, bm, 0)
con(bm, 0, bs, 0)

# (ms, message, bus), absolute times off one loadbang
STEPS = [
    (100, "put auto mode mode-1", "state"),
    (150, "put auto tempo 128", "state"),
    # the same key again: the replace case
    (200, "put auto mode mode-4", "state"),
]
x = 20
for ms, m, bus in STEPS:
    d = obj(x, 260, "del %d" % ms)
    mm = msg(x, 320, m)
    ss = obj(x, 380, "s %s" % bus)
    con(lb, 0, d, 0)
    con(d, 0, mm, 0)
    con(mm, 0, ss, 0)
    x += 460

# the restore bang, u_init's job in the real patch
txt(20, 700, "⛔ The 3600 ms must not be shortened. The bug this catches armed the flush from a loadbang at 3000 ms while u_init restores at ~3500 ms \\, so the write landed before the read \\, and a restore banged before 3000 never shows that order. The restore bang also arms the auto flush: u_state must never write a file it has "
    "not read \\, or a boot would overwrite the last session with its defaults.")
d = obj(20, 880, "del 3600")
rb = msg(20, 940, "bang")
con(lb, 0, d, 0)
con(d, 0, rb, 0)
con(rb, 0, st, 0)

# the commit
txt(1500, 700, "saveState is mother.pd's reserved name and nothing in Cut It may "
    "send it: a gate driver is not deployed.")
d = obj(1500, 880, "del 4200")
cm = msg(1500, 940, "bang")
cs = obj(1500, 1000, "s saveState")
con(lb, 0, d, 0)
con(d, 0, cm, 0)
con(cm, 0, cs, 0)

# self-quit: -send "pd quit" would return before any [del] fires
d = obj(2250, 880, "del 5400")
q = msg(2250, 940, "\\; pd quit")
con(lb, 0, d, 0)
con(d, 0, q, 0)

W = 2900
H = 1700
with open(OUT, "w") as fh:
    # No declare: the driver lives in a scratch directory, so state-assert.py
    # puts "Cut It" on the path itself.
    fh.write("#N canvas 20 20 %d %d 12;\n" % (W, H))
    fh.write("\n".join(B) + "\n")
    fh.write("\n".join(C) + "\n")
print("%s  %d boxes  %d cords  dir=%s" % (OUT, len(B), len(C), DIR))
