#!/usr/bin/env python3
"""Generates the timed driver for the display gate, into the scratch path given.

It pushes onto mode, disp, err, tempo, start and panic as a controller would.

DSP is off for the first windows: with no clock the grid has nothing to redraw,
so `idle-dsp-off` proves the dirty flag gates the repaint. Everything after it
needs DSP, because the beat row hangs off threshold~.

The 300 ms window is the display's form of item 234: every other window is
seconds in, so only a mode set before the grid paints can show that the first
painted frame keeps it.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20

SEQ = [
    # Nothing else in this run uses mode-8, so a lamp at index 10, the bottom
    # of the left column, can only have come from here.
    (300, "EARLY-MODE", ["\\; mode mode-8"], GAP),
    (4000, "idle-dsp-off", [], GAP),
    (8000, "dsp-on", ["\\; pd dsp 1"], GAP),
    # The mode is not re-sent: the next window asserts the one set at 300 ms
    # survived.
    (8600, "settling", ["\\; tempo 120"], GAP),
    (11000, "home-early-mode", [], GAP),
    (14000, "home-mode-1", ["\\; mode mode-1"], GAP),
    (17000, "home-mode-4", ["\\; mode mode-4"], GAP),
    (20000, "modal-45", ["\\; disp grid modal 45"], GAP),
    # u_err draws a warn on every page, so it reaches disp here: the grid must
    # ignore it, since it draws fails alone.
    (23000, "warn-ignored", ["\\; err warn u_bench quiet"], GAP),
    (26000, "alert-red", ["\\; err fail u_bench boom"], GAP),
    # the alert TTL is 2 s, so this window opens after it has expired
    (28500, "alert-expired", [], GAP),
    (31000, "home-again", ["\\; disp grid modal-off"], GAP),
    (34000, "beat-row", ["\\; start bang"], GAP),
    (41000, "after-panic", ["\\; panic bang"], GAP),
    (45000, "done", [], GAP),
]
QUIT_MS = 46000

BLURB = ("display-assert-drive -- GENERATED by display-assert-drive-gen.py. Do not "
         "edit this file. It drives the display arbiter: the dirty flag \\, the home "
         "layer and its mode lamp \\, a modal claiming the whole surface \\, an alert "
         "outranking it and expiring back to it \\, the beat row walking \\, and the "
         "surface going silent after a panic.")

NOTES = [
    "Run it through test/gate/display-assert.sh: it reads [t_midiout] in a scratch "
    "copy \\, and against the real Cut It every assertion passes vacuously.",

    "It needs DSP: the beat row hangs off threshold~ in c_clock. -noaudio leaves "
    "DSP running (item 280).",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: display-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/display-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="GRID",
                      taps=[], quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
