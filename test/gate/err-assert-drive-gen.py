#!/usr/bin/env python3
"""Generates the timed driver for the error-bus gate, into the scratch path given.

⛔ THE CLAIM: every warn and every fail is drawn, on every page (Brendan,
2026-11-04). Until then a perform class of modes hid warnings, and a filter
that quietens the error display fails in the direction of silence: its first
symptom would be a venue.

Each page window chooses a page and raises a warn in it; the fail after it does
not choose again, testing the state the choice left. One window puts the old
two-atom shape on the bus, `perform mode-6`, which is what used to hide a warn:
the old filter fails it, where a gate that only sent today's one-atom pages
would have passed the old code.

The 300 ms window is the only chance at the state before any page arrives.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 40

SEQ = [
    # Before any page has arrived.
    (300, "DEFAULT", ["\\; err warn u_gate before-mode"], GAP),

    # --- page 1 ------------------------------------------------------------
    (5000, "PAGE-1-WARN",
     ["\\; mode mode-1", "\\; err warn u_gate page-1-warn"], GAP),
    (5700, "PAGE-1-FAIL", ["\\; err fail u_gate page-1-fail"], GAP),

    # --- page 4, once a perform page ----------------------------------------
    (6400, "PAGE-4-WARN",
     ["\\; mode mode-4", "\\; err warn u_gate page-4-warn"], GAP),
    # Still on page 4: the page is not chosen again.
    (7100, "PAGE-4-FAIL", ["\\; err fail u_gate page-4-fail"], GAP),

    # --- the old shape, which the old filter read as perform ---------------
    # u_map refuses it as bad-mode, which is drawn too: the checks read
    # u_gate's own alerts.
    (7800, "OLD-PERFORM",
     ["\\; mode perform mode-6", "\\; err warn u_gate old-perform"], GAP),

    # --- info: logged and never drawn -------------------------------------
    # info-witness is a warn that must draw in the same window, so "info drew
    # nothing" cannot be satisfied by a dead display.
    (8500, "INFO",
     ["\\; mode mode-3", "\\; err warn u_gate info-witness",
      "\\; err info u_gate info-quiet"], GAP),

    # --- a level that is none of the three ---------------------------------
    (9200, "BAD-LEVEL", ["\\; err chatty u_gate bad-level"], GAP),

    (9900, "DONE", [], GAP),
]
QUIT_MS = 10600

BLURB = ("err-assert-drive -- GENERATED by err-assert-drive-gen.py. Do not edit this "
         "file. It drives u_err on every kind of page: warn and fail drawn on each \\, "
         "the old perform shape hiding nothing \\, info logged and never drawn \\, and a "
         "level that is none of the three.")

NOTES = [
    "Run it through test/gate/err-assert.sh \\, which also reads u_err's "
    "unconditional [print err] in the raw capture: that is what proves the log "
    "holds every error.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: err-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/err-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="ERR", taps=["disp", "err"],
                      quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
