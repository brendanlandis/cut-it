#!/usr/bin/env python3
"""Generates the timed driver for the tempo gate, into the scratch path given.

The windows are measurements: the analyser counts System Real-Time bytes over
a known span, so moving or shortening one changes the number it is checked
against.

The rate windows start at 4000 ms, after u_init restores saved state at about
3.5 s: a counting window straddling the restore could have its tempo changed
mid-count. The clamp and transport windows assert on events and are unaffected.

DSP goes on at 300 ms and stays on: the pulse is BPM / 60 * 24 into a [phasor~],
then [threshold~ 0.5 0 0.1 0] for one bang per cycle. -noaudio leaves DSP
running (item 280).

The tap windows press the nanoKONTROL's LOOP, as m_nano publishes it,
param xport-4, a fixed time apart, and read what reaches the tempo bus; the
phone's tempo goes in as a datagram into u_net's own port, /cutit tempo <bpm>,
as the phone sends it.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20
# u_net's inbound port in this copy: lib_scratch's state_dir writes CUTIT_INPORT into
# main-dev.pd's u_root box, or 9002 for a gate run by hand.
INPORT = int(os.environ.get("CUTIT_INPORT") or 9002)


def tap(at=0):
    """A press of the tap button, the nanoKONTROL's LOOP, which publishes its press alone, at <at>
    ms into the window."""
    return [(at, "\\; param xport-4 1")]


def pad(at=0):
    """A press of grid cell 21 and its release, at <at> ms into the window."""
    return [(at, "\\; param pad-21 127"), (at + 50, "\\; param pad-21 0")]


def phone(bpm):
    return "\\; tempo-cmd tempo %s" % bpm

# BPM / 60 * 24 Hz is 48 Hz at 120 BPM, so a two-second window holds 96 pulses
# per port.
SEQ = [
    (300, "DSP-ON", ["\\; pd dsp 1"], GAP),

    (4000, "RATE-120", [], GAP),                 # 4000..6000, 2 s at 120 BPM
    (6000, "SET-60", ["\\; tempo 60"], GAP),
    (6200, "RATE-60", [], GAP),                  # 6200..8200, 2 s at 60 BPM
    (8200, "SET-120", ["\\; tempo 120"], GAP),

    # An in-range tempo must not warn. [change] sits on the value, not the
    # verdict: filtering the flag would make a 500 warn and a following 5 silent.
    (8400, "IN-RANGE", [], GAP),
    # 5000 is clamped to 1000 BPM; the clock's own pulses top out near 284 Hz there, one in a block's
    # re-arm, and unclamped saturate at ~338.
    (9000, "TOO-HIGH", ["\\; tempo 5000"], GAP),
    (10000, "TOO-LOW", ["\\; tempo 0"], GAP),
    (11000, "BACK", ["\\; tempo 120"], GAP),

    (12000, "START", ["\\; start bang"], GAP),
    (13000, "STOP", ["\\; stop bang"], GAP),
    # Stop does not halt the clock: halting is the consumer's business.
    (13500, "AFTER-STOP", [], GAP),
    (15000, "PANIC", ["\\; panic bang"], GAP),
    # Knob 1 made live: with nothing Saved it is held at 120, 0.38 of its turn,
    # until turned through it; 0.3 is 103 BPM, on its line (u_map.lua).
    (15200, "KNOB-LIVE", ["\\; param og-knob-1 0.5", "\\; param og-knob-1 0.3"], GAP),

    # Tap tempo: the first tap starts the count, and each after it sets the
    # tempo from the intervals, 400 ms apart, 150 BPM.
    (15500, "TAP-1", tap(), GAP),
    (15900, "TAP-2", tap(), GAP),
    (16300, "TAP-3", tap(), GAP),
    # The tap's 150 holds knob 1 at 0.52, where its line puts 150 (Brendan,
    # 2026-11-04): 0.42, 128 BPM, is below it and moves nothing; 0.68, 183, is
    # through it and sets the tempo. Neither is a tap, so the count is untouched.
    (16700, "KNOB-HELD", ["\\; param og-knob-1 0.42"], GAP),
    (17100, "KNOB-THROUGH", ["\\; param og-knob-1 0.68"], GAP),
    # Two seconds and more after the last: it starts over, and sets nothing;
    # the next, 600 ms on, counts from it alone: 100 BPM.
    (18800, "TAP-GAP", tap(), GAP),
    (19400, "TAP-AFTER", tap(), GAP),
    # The phone's tempo, through u_net: one, one past the range, one that is
    # no number.
    (20000, "PHONE", [phone(133)], GAP),
    # ... and the phone's 133 holds it again, at 0.44: 0.7, 187 BPM, is above.
    (20200, "KNOB-PHONE", ["\\; param og-knob-1 0.7"], GAP),
    (20400, "PHONE-HIGH", [phone(2000)], GAP),
    (20800, "PHONE-BAD", [phone("fast")], GAP),
    # The drum page: cell 21 is a drum pad there, and presses on it set nothing.
    (21200, "PAGE-2", ["\\; mode drums"], GAP),
    (21400, "PAGE-2-TAPS", pad(0) + pad(400), GAP),
]
QUIT_MS = 22400

BLURB = ("tempo-assert-drive -- GENERATED by tempo-assert-drive-gen.py. Do not edit "
         "this file. It drives u_tempo: the pulse rate at two tempos \\, the clamp at "
         "both ends and its warning \\, the three transport bytes \\, and the fact that "
         "a stop does not halt the clock.")

NOTES = [
    "Run it through test/gate/tempo-assert.sh: it reads [t_midiout] in a scratch "
    "copy.",

    "It needs DSP: u_tempo's pulse is a [phasor~] read by [threshold~]. -noaudio "
    "leaves DSP running (item 280).",

    "The clock goes out on port 1 alone \\, for the Launchpad's animations: port 3 "
    "was the SP-404's \\, and the set of ports it reaches is asserted exactly.",

    "tempo-cmd is a bare name outside the allowlist \\, and safe: it exists only in this "
    "driver \\, in a gate's scratch copy. It carries a command to the socket below \\, which "
    "sends it to u_net's inbound port as the phone would.",
]


def socket(obj, msg, con):
    """/cutit <command> into u_net's port. It connects at 2600 ms: u_net's listen arms at
    2000, and a connect to a port with nothing bound survives one datagram (item 114)."""
    lb = obj(3000, 1300, "loadbang")
    dl = obj(3000, 1350, "del 2600")
    cm = msg(3000, 1400, "connect 127.0.0.1 %d" % INPORT)
    # Not a real netsend: gates run under -batch, which polls no socket (lib_scratch.net_direct).
    ns = obj(3000, 1600, "route send")
    gn = obj(3000, 1650, "s gate-net")
    con(ns, 0, gn, 0)
    rc = obj(3300, 1300, "r tempo-cmd")
    la = obj(3300, 1350, "list append")
    of = obj(3300, 1400, "oscformat cutit")
    lp = obj(3300, 1450, "list prepend send")
    lt = obj(3300, 1500, "list trim")
    for a, b in ((lb, dl), (dl, cm), (cm, ns), (rc, la), (la, of), (of, lp), (lp, lt), (lt, ns)):
        con(a, 0, b, 0)

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: tempo-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/tempo-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="CLK",
                      taps=["err", "tempo", "disp"], quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES,
                      extra=socket)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
