#!/usr/bin/env python3
"""Generates the driver and the harness for the audio gate.

    audio-assert-drive-gen.py OUT-DRIVE.pd OUT-HARNESS.pd STATEDIR WAVPATH

The harness instantiates u_root alone, not main-dev.pd: catch~ must be unique
and u_mother-stub already holds catch~ outL and outR. u_root loads clean on its
own, since every mother name its children use is an ordinary receive.

220 Hz left and 330 Hz right, as u_mother-stub has them, because a swap is the
failure that matters (L is the SP-404's drums, item 11) and only the frequencies
can see one: both channels carry the same level.

One recording, cut by time into segments, with 300 ms guard bands either side of
each boundary, since a message-domain start is not sample-aligned.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 40

# The analyzer's unity check compares against this. 0.25 leaves 12 dB of
# headroom, so a passthrough that summed both channels shows as a level error
# rather than as clipping.
AMP = 0.25

# Seconds from the start of the recording. The analyzer imports this table
# rather than keeping a copy of it.
REC_MS = 2000
SEGMENTS = [("silence", 0.0, 1.0), ("both", 1.0, 3.0),
            ("left", 3.0, 5.0), ("right", 5.0, 7.0), ("tail", 7.0, 8.0)]
GUARD = 0.3


def _seq(wav):
    at = lambda s: REC_MS + int(s * 1000)
    return [
        # The open before the start: writesf~ silently writes nothing to a file
        # it was never given.
        (300, "DSP", ["\\; pd dsp 1"], GAP),
        (REC_MS, "REC", ["\\; aud-cmd open %s" % wav, "\\; aud-cmd start"], GAP),

        (at(1.0), "BOTH", ["\\; aud-l %g" % AMP, "\\; aud-r %g" % AMP], GAP),
        (at(3.0), "LEFT", ["\\; aud-r 0"], GAP),
        (at(5.0), "RIGHT", ["\\; aud-l 0", "\\; aud-r %g" % AMP], GAP),
        (at(7.0), "TAIL", ["\\; aud-r 0"], GAP),

        # Stop before quit: writesf~ fixes up the WAV header on stop, and a file
        # killed mid-write declares a length it does not have.
        (at(8.0), "STOP", ["\\; aud-cmd stop"], GAP),
        (at(9.0), "DONE", [], GAP),
    ]


BLURB = ("audio-assert-drive -- GENERATED by audio-assert-drive-gen.py. Do not edit "
         "this file. It turns two oscillators on and off in the harness beside it "
         "and records u_root's OUTPUT to a soundfile: both channels \\, then left "
         "alone \\, then right alone.")

NOTES = [
    "Run it through test/gate/audio-assert.sh \\, which loads the harness beside "
    "it: on its own this drives receives nothing listens to and writes no file.",
]

HARNESS_BLURB = (
    "audio-assert-harness -- GENERATED by audio-assert-drive-gen.py. Do not edit "
    "this file. It instantiates u_root alone (u_mother-stub already holds the "
    "catch~ pair) \\, feeds its inputs from two oscillators \\, and records its "
    "output.")

HARNESS_NOTE = (
    "u_root's audio path has no gain \\, so the file written here should be the "
    "file sent in \\, channel for channel. aud-l \\, aud-r and aud-cmd are bare "
    "globals outside the C-2 allowlist: this file exists only in a scratch "
    "directory.")


def write_harness(path, statedir):
    B, C = [], []

    def obj(x, y, s):
        B.append("#X obj %d %d %s;" % (x, y, s)); return len(B) - 1

    def txt(x, y, s, w):
        B.append("#X text %d %d %s, f %d;" % (x, y, s, w)); return len(B) - 1

    txt(20, 20, HARNESS_BLURB, 92)

    # main-dev.pd's creation arguments with the state directory changed, all but
    # the sixth (u_net's inbound port), which this harness does not pass. Pd 0.49
    # does not warn about a wrong count.
    root = obj(20, 260, "u_root 17 1 %s 33 49" % statedir)

    osc_l = obj(20, 420, "osc~ 220")
    amp_l = obj(20, 470, "*~ 0")
    r_l = obj(200, 420, "r aud-l")
    snd_l = obj(20, 520, "s~ inL")
    C += [(osc_l, 0, amp_l, 0), (r_l, 0, amp_l, 1), (amp_l, 0, snd_l, 0)]

    osc_r = obj(500, 420, "osc~ 330")
    amp_r = obj(500, 470, "*~ 0")
    r_r = obj(680, 420, "r aud-r")
    snd_r = obj(500, 520, "s~ inR")
    C += [(osc_r, 0, amp_r, 0), (r_r, 0, amp_r, 1), (amp_r, 0, snd_r, 0)]

    cat_l = obj(980, 420, "catch~ outL")
    cat_r = obj(1180, 420, "catch~ outR")
    cmd = obj(1400, 420, "r aud-cmd")
    wsf = obj(980, 540, "writesf~ 2")
    C += [(cat_l, 0, wsf, 0), (cat_r, 0, wsf, 1), (cmd, 0, wsf, 0)]

    txt(20, 640, HARNESS_NOTE, 92)

    out = ["#N canvas 20 20 1900 900 12;"] + B \
        + ["#X connect %d %d %d %d;" % t for t in C]
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    return len(B), len(C)


if __name__ == "__main__":
    if len(sys.argv) < 5:
        sys.exit("usage: audio-assert-drive-gen.py OUT-DRIVE.pd OUT-HARNESS.pd "
                 "STATEDIR WAVPATH  (run it through test/gate/audio-assert.sh)")
    seq = _seq(sys.argv[4])
    w, b, c = D.build(sys.argv[1], seq, tag="AUDIO", taps=["disp"],
                      quit_ms=REC_MS + 10000, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
    hb, hc = write_harness(sys.argv[2], sys.argv[3])
    print("%s  u_root + 2 osc~ + writesf~  %d boxes  %d connects"
          % (sys.argv[2], hb, hc))
