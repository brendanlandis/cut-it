#!/usr/bin/env python3
"""Generates the timed driver for the debug patch's gate, into the scratch path.

It loads "Cut It Debug"/main.pd, which has no u_mother-stub, disp or g_oled,
so the stimulus and the readback are mother's own names: `notes` in,
screenLine1 to 5 out.

The patch repaints at 3.3 Hz, so a window holds many copies of each row and
the analyser asks whether a row appeared, never how often: a count would depend
on where a 300 ms metro tick lands.

The window at 600 ms opens before the wire.sh fork's 1500 ms delay, and the one
at 2200 ms proves the fork happened (item 234: time windows from behavior).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 40

# The channel is the port: wire.sh puts the Launchpad on Pd channels 1-16, the
# nano on 17-32 and the Uno on 49-64. Port 3, 33-48, was the SP-404's and has
# nothing on it now, but keeps its counter. 16 and 17 are there because an
# off-by-one in (channel-1)/16 shows only at a boundary.
SEQ = [
    (600, "EARLY", [], GAP),

    (2200, "BOOTED", [], GAP),

    # t_notein takes <pitch> <velocity> <channel>; t_ctlin <value> <controller>
    # <channel>.
    (2600, "LP-LOW", ["\\; t-notein 60 100 1"], GAP),
    (3000, "LP-HIGH", ["\\; t-ctlin 64 80 16"], GAP),
    (3400, "NANO", ["\\; t-ctlin 40 5 17"], GAP),
    (3800, "PORT3", ["\\; t-notein 48 100 33"], GAP),

    # The Uno block has no counter row, so its traffic must show on the
    # channel row.
    (4200, "UNO", ["\\; t-notein 72 100 49"], GAP),

    # Every press is followed by its release at velocity 0: one that got past
    # the patch's velocity gate would fire a probe twice, which the sent
    # counter shows.
    (4600, "HELP", ["\\; notes 66 100", "\\; notes 66 0"], GAP),
    (5200, "ERRLOG", ["\\; notes 63 100", "\\; notes 63 0"], GAP),
    (5800, "NETWORK", ["\\; notes 64 100", "\\; notes 64 0"], GAP),
    (6400, "REWIRE-SCREEN", ["\\; notes 65 100", "\\; notes 65 0"], GAP),
    (7000, "TESTOUT", ["\\; notes 62 100", "\\; notes 62 0"], GAP),

    (7600, "VOLCA", ["\\; notes 72 100", "\\; notes 72 0"], GAP),
    # k15 fired the SP-404's probe until it left the rig: unbound now, and it
    # must send nothing.
    (8400, "K15", ["\\; notes 74 100", "\\; notes 74 0"], GAP),

    # k17 does not change screen, so its count is read on screen 5 afterwards.
    (9200, "REWIRE-KEY", ["\\; notes 76 100", "\\; notes 76 0"], GAP),
    (9800, "REWIRE-VIEW", ["\\; notes 65 100", "\\; notes 65 0"], GAP),

    # A select with a connected reject outlet would act on every key.
    (10400, "UNBOUND", ["\\; notes 79 100", "\\; notes 79 0"], GAP),

    (11000, "EXIT", ["\\; notes 60 100", "\\; notes 60 0"], GAP),

    (11600, "DONE", [], GAP),
]
QUIT_MS = 12200

BLURB = ("debug-assert-drive -- GENERATED by debug-assert-drive-gen.py. Do not edit "
         "this file. It drives Cut It Debug: one MIDI event per channel block \\, "
         "every screen key \\, the Volca probe \\, a re-wire \\, two unbound keys "
         "and the exit.")

NOTES = [
    "Run it through test/gate/debug-assert.sh: it needs the scratch copy with "
    "notein \\, ctlin and noteout rewritten to printing stubs and shell to t_shell.",

    "The rows repeat about three times a second on the repaint metro \\, so assert "
    "that a row appeared in a window \\, never how often.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: debug-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/debug-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="DBG",
                      taps=["screenLine1", "screenLine2", "screenLine3",
                            "screenLine4", "screenLine5", "goHome"],
                      quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
