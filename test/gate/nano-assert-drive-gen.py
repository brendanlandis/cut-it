#!/usr/bin/env python3
"""Generates the timed driver for the nanoKONTROL gate, into the scratch path given.

The atoms are in outlet order, `t-ctlin <value> <controller> <channel>`:
t_ctlin is an [unpack f f f] wired outlet for outlet.

One t-ctlin reaches both rewritten [ctlin] boxes (the gate skill), so the last
two windows drive the Launchpad's channel, the liveness witness for the
cross-talk checks, and channel 33, Pd's port 3, where nothing may answer since
the SP-404 left the rig.

The 300 ms window is the boot's form of item 234: m_nano needs no table and no
restore, so it must decode from the first millisecond.

CC 2 goes out on four channels with four values: 17 and 18 both decode to
`slider-2`, so equal values could not tell one arriving twice from both once.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 40

SEQ = [
    # --- before anything has settled ---------------------------------------
    (300, "EARLY", ["\\; t-ctlin 64 1 17"], GAP),

    # --- the channel gate: 17 and 18 in, everything else out ---------------
    # A distinct value each, so the analyzer can say which channel emitted.
    (5000, "CH-16", ["\\; t-ctlin 10 2 16"], GAP),
    (5700, "CH-17", ["\\; t-ctlin 11 2 17"], GAP),
    (6400, "CH-18", ["\\; t-ctlin 12 2 18"], GAP),
    (7100, "CH-19", ["\\; t-ctlin 13 2 19"], GAP),

    # --- the five name families, one window each ---------------------------
    (7800, "SLIDER", ["\\; t-ctlin 21 3 17"], GAP),
    (8500, "KNOB", ["\\; t-ctlin 22 15 17"], GAP),
    (9200, "BTN-T", ["\\; t-ctlin 127 22 17"], GAP),
    (9900, "BTN-B", ["\\; t-ctlin 127 34 17"], GAP),
    (10600, "XPORT", ["\\; t-ctlin 127 43 18"], GAP),

    # --- press only, and the release is the point --------------------------
    # Both halves in one window: nothing emitted fails it, and so do two.
    (11300, "PRESS-RELEASE",
     ["\\; t-ctlin 127 24 17", "\\; t-ctlin 0 24 17"], GAP),

    # --- a CC in the block that decodes to no known kind -------------------
    (12000, "UNMAPPED", ["\\; t-ctlin 99 55 17"], GAP),

    # --- the stale-flag trap, after a continuous control and after a button --
    # A stale is-cont would leak the raw value under the last name, a stale
    # is-btn a 1.
    (12700, "STALE-CONT",
     ["\\; t-ctlin 30 7 17", "\\; t-ctlin 99 55 17"], GAP),
    (13400, "STALE-BTN",
     ["\\; t-ctlin 127 26 17", "\\; t-ctlin 127 56 17"], GAP),

    # --- the other two channel blocks, through the same stub ---------------
    # 33 is Pd's port 3, the SP-404's until it left the rig: nothing listens.
    (14100, "CH-33", ["\\; t-ctlin 77 20 33"], GAP),
    # CC 19, the bottom of the right column: the left column's are mode keys.
    (14800, "CH-LP", ["\\; t-ctlin 55 19 1"], GAP),


    (15500, "DONE", [], GAP),
]
QUIT_MS = 16200

BLURB = ("nano-assert-drive -- GENERATED by nano-assert-drive-gen.py. Do not edit "
         "this file. It drives m_nano through t_ctlin: the channel gate \\, the five "
         "name families \\, buttons on press only \\, the unmapped-CC warning and the "
         "flag clears behind it \\, and the Launchpad's channel block and Pd's port 3's.")

NOTES = [
    "Run it through test/gate/nano-assert.sh \\, which rewrites [ctlin] to "
    "[t_ctlin] in a scratch copy: against the real Cut It nothing reaches m_nano.",

    "t-ctlin carries <value> <controller> <channel> in outlet order \\, so the "
    "unpack fires right to left as [ctlin] does.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: nano-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/nano-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="NANO",
                      taps=["param", "disp", "err"], quit_ms=QUIT_MS,
                      blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
