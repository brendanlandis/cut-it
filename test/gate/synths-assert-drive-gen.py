#!/usr/bin/env python3
"""Generates the timed driver for the synths gate, into the scratch path it is given.

The copy boots on page 3 with strings saved, restored at about 3.5 s, so every window
opens after the restore: the first key is the proof the choice came back. The nanoKEY's
keys go in through t-notein, as m_nanokey's [notein] hears them; the Launchpad's page-3 pads
as param pad-NN, the names m_launchpad publishes (launchpad-assert holds the decode); the
phone's command as a datagram into u_net's own port, /cutit synth <choice>, as the phone
sends it.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20
# u_net's inbound port in this copy: lib_scratch's state_dir writes CUTIT_INPORT into
# main-dev.pd's u_root box, or 9002 for a gate run by hand.
INPORT = int(os.environ.get("CUTIT_INPORT") or 9002)


def key(note, vel, ch=49):
    return "\\; t-notein %d %d %d" % (note, vel, ch)


def pad(n, v):
    return "\\; param pad-%d %d" % (n, v)


def phone(choice):
    return "\\; synths-cmd synth %s" % choice


SEQ = [
    # strings came back at the restore: a key plays the Streichfett, and nothing else
    (4500, "KEY-RESTORED", [key(60, 100)], GAP),
    (4800, "KEY-RESTORED-OFF", [key(60, 0)], GAP),
    # FM's pad on page 3, a press and its release
    (5100, "PAD-FM", [(0, pad(22, 127)), (100, pad(22, 0))], GAP),
    # any channel of the nanoKEY's port: channel 2 of it, 50
    (5400, "KEY-FM", [key(62, 100, 50)], GAP),
    (5700, "KEY-FM-OFF", [key(62, 0, 50)], GAP),
    # a key held through a switch: pressed on fm, the phone chooses strings, released
    (6000, "HOLD", [key(64, 100)], GAP),
    (6300, "PHONE-STRINGS", [phone("strings")], GAP),
    (6600, "HOLD-OFF", [key(64, 0)], GAP),
    (6900, "KEY-STRINGS", [(0, key(65, 100)), (100, key(65, 0))], GAP),
    # strings' pad while strings is chosen: no change, nothing said
    (7200, "PAD-SAME", [(0, pad(26, 127)), (100, pad(26, 0))], GAP),
    # both pads held: FM down, STRINGS down, FM up, STRINGS up. Only presses choose, so
    # the choice ends on strings; a release that chose would end it on fm
    (7350, "TWO-PADS", [(0, pad(22, 127)), (40, pad(26, 127)), (80, pad(22, 0)),
                        (120, pad(26, 0))], GAP),
    # notes on the other ports: the nano's, the Streichfett's own panel, its port's last,
    # and a fifth port's first, which a device on Midi-In 5 would send
    (7500, "OTHER-PORTS", [key(66, 100, 17), key(67, 100, 33), key(68, 100, 48),
                           key(70, 100, 65)], GAP),
    # page 1: the pads mean nothing there, and the nanoKEY still plays the choice
    (7800, "MODE-1", ["\\; mode mode-1"], GAP),
    (8000, "PAD-OFF-PAGE", [(0, pad(22, 127)), (100, pad(22, 0))], GAP),
    (8300, "KEY-OFF-PAGE", [(0, key(69, 100)), (100, key(69, 0))], GAP),
    # a choice c_synth does not know, from the phone
    (8600, "BAD", [phone("organ")], GAP),
    (8900, "PANIC", ["\\; panic 1"], GAP),
    # the auto flush is u_state's 2 s clock: the last change, at 6.3 s, is on disk by now
    (9200, "SETTLE", [], GAP),
]
QUIT_MS = 10200

BLURB = ("synths-assert-drive -- GENERATED by synths-assert-drive-gen.py. Do not edit this "
         "file. It plays the nanoKEY into c_synth \\, switches the synth from a page-3 pad and "
         "from the phone \\, holds a key through a switch \\, and panics \\, in a copy of the "
         "instrument booted on page 3 with strings saved.")

NOTES = [
    "Run it through test/gate/synths-assert.sh: it rewrites notein \\, noteout and ctlout to "
    "stubs in a scratch copy. Against the real patch it would send real MIDI.",
    "synths-cmd is a bare name outside the allowlist \\, and safe: it exists only in this "
    "driver \\, in a gate's scratch copy. It carries a command to the socket below \\, which "
    "sends it to u_net's inbound port as the phone would.",
]


def socket(obj, msg, con):
    """/cutit <command> into u_net's port. It connects at 2600 ms: u_net's listen arms at
    2000, and a connect to a port with nothing bound survives one datagram (item 114)."""
    lb = obj(3000, 1300, "loadbang")
    dl = obj(3000, 1350, "del 2600")
    cm = msg(3000, 1400, "connect 127.0.0.1 %d" % INPORT)
    ns = obj(3000, 1600, "netsend -u -b")
    rc = obj(3300, 1300, "r synths-cmd")
    la = obj(3300, 1350, "list append")
    of = obj(3300, 1400, "oscformat cutit")
    lp = obj(3300, 1450, "list prepend send")
    lt = obj(3300, 1500, "list trim")
    for a, b in ((lb, dl), (dl, cm), (cm, ns), (rc, la), (la, of), (of, lp), (lp, lt), (lt, ns)):
        con(a, 0, b, 0)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: synths-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/synths-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="SYNTHS", taps=["param", "err", "state"],
                      quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES, extra=socket)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
