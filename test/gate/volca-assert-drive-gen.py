#!/usr/bin/env python3
"""Generates the timed driver for the Volca gate, into the scratch path it is given.

The CC at 300 ms is before u_map reads its table (item 234).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20

SEQ = [
    (300, "EARLY", ["\\; param gk-cc 64"], GAP),
    (2600, "VOLCA-CC", ["\\; param gk-cc 64"], GAP),
    (2700, "VOLCA-NOTE", ["\\; param gk-note 100"], GAP),
    (2800, "VOLCA-PROG", ["\\; param gk-prog 100"], GAP),

    # volca-key: the note-off comes from the key, as velocity 0, where
    # volca-note's fixed 200 ms would release a held key itself.
    (2900, "VOLCA-KEY-ON", ["\\; param gk-key 100"], GAP),
    # The held window is the only one that tells a key from makenote, which also
    # puts an on and then an off on the wire. It opens 150 ms after the press and
    # runs to the release, straddling makenote's 200 ms, and sends nothing.
    (3050, "VOLCA-KEY-HELD", [], GAP),
    (3500, "VOLCA-KEY-OFF", ["\\; param gk-key 0"], GAP),

    # The key path bypasses makenote, so a note can be left sounding.
    (3800, "VOLCA-PANIC", ["\\; panic 1"], GAP),
]
QUIT_MS = 4800

BLURB = ("volca-assert-drive -- GENERATED by volca-assert-drive-gen.py. Do not edit "
         "this file. It drives m_volca through the map: a control change \\, a note \\, "
         "a program change \\, a held key and its release \\, and panic \\, each on "
         "the Volca's own channel.")

NOTES = [
    "Run it through test/gate/volca-assert.sh: it rewrites noteout \\, ctlout and "
    "pgmout to printing stubs in a scratch copy and appends its own map rows. "
    "Against the real patch it would send real MIDI.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: volca-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/volca-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="VOLCA",
                      taps=["param", "err"], quit_ms=QUIT_MS,
                      blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
