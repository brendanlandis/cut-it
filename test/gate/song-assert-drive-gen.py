#!/usr/bin/env python3
"""Generates the song gate's timed drivers, into the scratch paths it is given.

    python3 test/gate/song-assert-drive-gen.py <out.pd> [play | reload | legacy | songs]

play, the first run: the copy boots on the drum page with a song of three sections saved, intro,
verse and chorus, and the top row, save and revert are pressed as the Launchpad sends them, param
lp-cc-<n> 127 then 0 (launchpad-assert holds the decode); the transport runs on the start and stop
buses, and a change is a tempo on the tempo bus, which u_tempo puts as the section's. reload, the
second: the same state directory, what the first left on disk, loaded again, and reverted. legacy,
the third: a state directory from before sections, the drum pattern and the synth choice in the
auto file, loaded once. songs, the fourth: three songs and a setlist saved, the Organelle's keys
pressed as m_organelle publishes them, param og-key-<n> <velocity>, stopped and
playing.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20


def cc(n, v):
    return "\\; param lp-cc-%d %d" % (n, v)


def press(n):
    """A Launchpad CC button: its press, and its release 100 ms later."""
    return [(0, cc(n, 127)), (100, cc(n, 0))]


# PLAY brings the performance page up, and row 1's left button takes it back to the drum page, in
# one instant, so no frame the gate reads shows anything else.
PLAY_DRUMS = "\\; start bang \\; param lp-cc-80 127 \\; param lp-cc-80 0"


# Every window opens after u_song's load at about 3.5 s, u_init's restore. The song's tempos and
# loops (song-assert.py's seed): intro 200 BPM, verse 240 with a length of two loops, chorus 180
# with a loop of 32 steps; verse's tempo is 160 from SAVE on. At 160 verse's loop of 8 steps is
# 0.75 s, so PLAY at 6.3 s plays two and hands over to chorus at about 7.8; chorus's loop is 2.67 s
# at 180, so intro, queued at 8.3, starts at about 10.5.
PLAY = [
    # DSP on: the steps are cut from a phasor~, and the grid's clock, which the queued
    # section's blink follows, is one too
    (4000, "LOADED", ["\\; pd dsp 1"], GAP),
    (4200, "PRESS-STOPPED", press(94), GAP),
    (4700, "EDIT", ["\\; tempo 150"], GAP),
    (5100, "REVERT", press(8), GAP),
    (5500, "EDIT-2", ["\\; tempo 160"], GAP),
    (5900, "SAVE", press(108), GAP),
    (6300, "PLAY", [PLAY_DRUMS], GAP),
    (7600, "HANDOVER", [], GAP),
    (8300, "QUEUE", press(93), GAP),
    (10300, "AT-LOOP", [], GAP),
    (11000, "STOP", ["\\; stop bang"], GAP),
    (11300, "FORWARD", press(92), GAP),
    (11700, "BACK", press(91), GAP),
    (12100, "EMPTY-BUTTON", press(97), GAP),
    (12400, "FINAL-EDIT", ["\\; tempo 170"], GAP),
    # the draft's timer is every 2 s from the load: the last change is on disk by 13.5 s
    (14400, "FLUSHED", [], GAP),
]
RELOAD = [
    (4000, "LOADED", [], GAP),
    (4300, "REVERT", press(8), GAP),
    (6000, "FLUSHED", [], GAP),
]
# u_state's auto flush, 2 s after its restore, and the song's first flush, at its load.
LEGACY = [(6000, "FLUSHED", [], GAP)]


def key(n):
    """An Organelle key, n from the lowest: its press and its release, as m_organelle publishes
    them (organelle-assert holds the decode)."""
    return [(0, "\\; param og-key-%d 100" % (59 + n)), (100, "\\; param og-key-%d 0" % (59 + n))]


# songs, the fourth run: three songs and a setlist saved, gig, its keys 1 lantern, 2 hollow bell and 3
# night drive; night drive loaded at load (song-assert.py's SONGS). Lantern's and hollow bell's loops
# are 32 steps, about 2 s at their 240 and 230 BPM, so a song queued waits long enough for the next
# arrow to blink. PLAY at 5.1 s: the pattern comes round at about 7.1 s and hollow bell takes over; its
# pattern at about 9.2, 11.3.
SONGS = [
    (4000, "LOADED", ["\\; pd dsp 1"], GAP),
    (4200, "KEY-STOPPED", key(2), GAP),
    (4500, "EDIT", ["\\; tempo 230"], GAP),
    (4800, "KEY-BACK", key(1), GAP),
    (5100, "PLAY", ["\\; start bang"], GAP),
    (5300, "KEY-BAR", key(2), GAP),
    (6900, "AT-BAR", [], GAP),
    (7600, "NEXT", press(92), GAP),
    (8000, "BACK", press(91), GAP),
    (9700, "NEXT-AGAIN", press(92), GAP),
    (11000, "AT-NEXT-BAR", [], GAP),
    (11900, "KEY-STOP", key(1) + [(150, "\\; stop bang")], GAP),
    (12400, "KEY-PAST", key(4), GAP),
    # the draft's timer is every 2 s from the load: the index is on disk by 13.5 s
    (13800, "FLUSHED", [], GAP),
]
RUNS = {"play": (PLAY, 14600), "reload": (RELOAD, 6200), "legacy": (LEGACY, 6200),
        "songs": (SONGS, 14000)}

BLURB = ("song-assert-drive -- GENERATED by song-assert-drive-gen.py. Do not edit this file. It "
         "presses the Launchpad's top row \\, save and revert \\, runs the transport and changes "
         "the tempo \\, in a copy of the instrument whose state directory holds a song.")
NOTES = [
    "Run it through test/gate/song-assert.sh: it rewrites midiout and pgmout to stubs in a "
    "scratch copy. Against the real patch it would send real MIDI.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: song-assert-drive-gen.py OUT.pd [play|reload|legacy|songs]  (run it through "
                 "test/gate/song-assert.sh, which passes a scratch path)")
    seq, quit_ms = RUNS[sys.argv[2] if len(sys.argv) > 2 else "play"]
    w, b, c = D.build(sys.argv[1], seq, tag="SONG", taps=["state", "tempo", "err", "start", "stop"],
                      quit_ms=quit_ms, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
