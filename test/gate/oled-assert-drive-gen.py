#!/usr/bin/env python3
"""Generates the timed driver for the OLED gate, into the scratch path given.

The gate taps oscOut and asserts on the gPrintln text.

Every window is at least 700 ms: g_oled repaints on a [metro 100], and a window
of a few frames can miss the repaint and report a blank screen.

The windows straddle the TTLs on ref/module/display.md: param 1200 ms, warn
2000 ms, fail 4000 ms. The fail is checked twice, once where a warn would be
gone and once after its own TTL.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 40

SEQ = [
    # Nothing before 4500 ms: u_init's `booting` modal holds the screen until
    # its modal-off at about 3500 ms. A tempo on the bus, which home drew in a
    # footer until 2026-11-04: nothing at rest names it now.
    (4500, "HOME", ["\\; tempo 140"], GAP),

    # --- a parameter, and its 1200 ms TTL ---------------------------------
    # The "it is up" window must be shorter than the TTL it asserts: up in
    # 800 ms, gone in the next window.
    (5500, "PARAM", ["\\; disp gate-p1 11"], GAP),
    (6300, "PARAM-GONE", [], GAP),

    # And it must not come back: with the store's aging broken, a new parameter
    # would raise the layer again and redraw the old one beside it.
    (8200, "PARAM-AGAIN", ["\\; disp gate-p2 22"], GAP),

    # Lets the store age out: 13 frames is 1.3 s, and anything sooner than about
    # 1.8 s leaves the last parameter holding a row, so the fifth of the five
    # below is refused instead of the sixth.
    (9000, "PARAM-AGED", [], GAP),

    # --- the five-row store, and the sixth that must be refused -----------
    (10800, "FIVE", ["\\; disp gate-a 1", "\\; disp gate-b 2", "\\; disp gate-c 3",
                     "\\; disp gate-d 4", "\\; disp gate-e 5"], GAP),
    (11400, "SIXTH", ["\\; disp gate-f 6"], GAP),

    # All five, in reverse: one re-touched row would see the other four age out
    # from under it, and e,d,c,b,a is the one order where a stable store and a
    # reordering one give different answers.
    (11900, "IN-PLACE", ["\\; disp gate-e 55", "\\; disp gate-d 44",
                         "\\; disp gate-c 33", "\\; disp gate-b 22",
                         "\\; disp gate-a 99"], GAP),

    # --- modal outranks param ---------------------------------------------
    (12600, "MODAL", ["\\; disp modal gate-modal"], GAP),
    (13600, "MODAL-PARAM", ["\\; disp gate-p9 99"], GAP),

    # --- alert outranks modal, and gives it back --------------------------
    # Longer than the alert: its first frame shows the alert won, its last that
    # the alert gave the screen back.
    (14600, "ALERT", ["\\; err warn u_gate gate-alert"], GAP),
    (17600, "ALERT-GONE", [], GAP),

    # A fail lasts twice as long as a warn; these two windows tell them apart.
    (18400, "FAIL", ["\\; err fail u_gate gate-fail"], GAP),
    (20900, "FAIL-STILL", [], GAP),
    (23200, "FAIL-GONE", [], GAP),

    # --- and the modal is cleared explicitly ------------------------------
    (24000, "MODAL-OFF", ["\\; disp modal-off"], GAP),

    # --- the two reserved selectors that are not the OLED's ----------------
    (24800, "RESERVED", ["\\; disp led running", "\\; disp grid modal 45"], GAP),

    # --- the diag layer, and the roster it draws ---------------------------
    # Summoned once: the layer holds state, so the presence changes below show
    # without a second summon, and the TTL windows at the end measure from here.
    (26600, "DIAG", ["\\; disp diag"], GAP),

    # knob1 makes m_organelle, a passive layer, publish `seen`, and a key on the
    # nanoKEY's channel block, 49, m_nanokey, the other (2026-11-04).
    (27600, "DIAG-SEEN", ["\\; presence seen m_nano", "\\; knob1 0.5",
                          "\\; t-notein 60 100 49", "\\; t-notein 60 0 49"], GAP),
    (28600, "DIAG-GONE", ["\\; presence lost m_nano"], GAP),

    # m_launchpad has never answered, so this `lost` must leave it `never`.
    (29600, "DIAG-NEVER", ["\\; presence lost m_launchpad"], GAP),

    # An alert covers it: a layer that always won would pass every check above.
    # The 2 s warn clears with diag's own 8 s TTL still running.
    (30600, "DIAG-ALERT", ["\\; err warn u_gate gate-diagx"], GAP),
    (33000, "DIAG-BACK", [], GAP),
    (35200, "DIAG-TTL", [], GAP),

    (36200, "DONE", [], GAP),
]
QUIT_MS = 37000

BLURB = ("oled-assert-drive -- GENERATED by oled-assert-drive-gen.py. Do not edit "
         "this file. It drives g_oled's five layers over the disp bus: a parameter "
         "and its TTL \\, five rows and a refused sixth \\, a modal \\, an alert "
         "outranking it \\, the longer fail TTL \\, the two reserved selectors \\, "
         "and the diag roster with an alert drawn over the top of it.")

NOTES = [
    "Run it through test/gate/oled-assert.sh \\, which taps oscOut: without the "
    "tap the capture holds no drawing.",

    "The tap does not break C-5 \\, which governs writing: a listener cannot change "
    "what the screen is told.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: oled-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/oled-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="OLED",
                      taps=["oscOut", "disp", "err", "presence"], quit_ms=QUIT_MS,
                      blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
