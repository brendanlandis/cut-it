#!/usr/bin/env python3
"""Generates the timed driver for the error-bus gate, into the scratch path given.

⛔ THE CENTRAL CLAIM HERE IS ONE NOBODY HAS EVER TESTED HEADLESSLY: that perform
mode suppresses `warn` but NEVER suppresses `fail`. It was bench prose only.
plan-v04.md notes that a mode split weighted toward perform silently quietens the
error display -- a failure whose first symptom is a venue, at the moment the
instrument is least able to tell you anything.

Each mode window sets the mode and raises one action apart, testing the
transition; the perform fail window does not re-send the mode, testing the state
the transition left.

The 300 ms window is the only chance at the verbose default: nothing puts u_err
back into "no mode has ever arrived", which is the state the instrument boots in.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 40

SEQ = [
    # Before any mode has arrived.
    (300, "DEFAULT", ["\\; err warn u_gate before-mode"], GAP),

    # --- compose: everything shows ----------------------------------------
    (5000, "COMPOSE-WARN",
     ["\\; mode compose mode-1", "\\; err warn u_gate compose-warn"], GAP),
    (5700, "COMPOSE-FAIL", ["\\; err fail u_gate compose-fail"], GAP),

    # --- perform: warn is dropped and fail is not --------------------------
    (6400, "PERFORM-WARN",
     ["\\; mode perform mode-4", "\\; err warn u_gate perform-warn"], GAP),
    # Still in perform: the mode is not re-sent.
    (7100, "PERFORM-FAIL", ["\\; err fail u_gate perform-fail"], GAP),

    # --- back to compose, so the filter is proved to be reversible ---------
    (7800, "BACK-TO-COMPOSE",
     ["\\; mode compose mode-2", "\\; err warn u_gate back-warn"], GAP),

    # --- a two-atom mode, which is what u_map actually sends ---------------
    # route matches the selector, so `perform mode-6` must filter as a bare
    # `perform` does.
    (8500, "TWO-ATOM-MODE",
     ["\\; mode perform mode-6", "\\; err warn u_gate two-atom"], GAP),

    # --- info: logged and never drawn -------------------------------------
    # In compose, since in perform the mode filter would answer for the level.
    # info-witness is a warn that must draw in the same window, so "info drew
    # nothing" cannot be satisfied by a dead display.
    (9200, "INFO",
     ["\\; mode compose mode-3", "\\; err warn u_gate info-witness",
      "\\; err info u_gate info-quiet"], GAP),

    # --- a level that is none of the three ---------------------------------
    (9900, "BAD-LEVEL", ["\\; err chatty u_gate bad-level"], GAP),

    (10600, "DONE", [], GAP),
]
QUIT_MS = 11300

BLURB = ("err-assert-drive -- GENERATED by err-assert-drive-gen.py. Do not edit this "
         "file. It drives u_err's mode filter: warn suppressed in perform and passed "
         "in compose \\, fail passed in BOTH \\, the two-atom mode form \\, and a "
         "level that is neither.")

NOTES = [
    "Run it through test/gate/err-assert.sh \\, which also reads u_err's "
    "unconditional [print err] in the raw capture: that is what proves the log is "
    "never filtered when the screen is.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: err-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/err-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="ERR", taps=["disp", "err"],
                      quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
