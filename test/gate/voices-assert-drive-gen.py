#!/usr/bin/env python3
"""Generates the timed driver for the voices gate, into the scratch path given.

It presses the Launchpad's columns, aux, Setup and the nanoKONTROL on param, as their layers publish
them, and the phone's voice page over OSC, in a copy of the instrument with no song saved, so the
voices are the seed's: row 1 drums, row 2 harmony, row 3 melody.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20
# u_net's inbound port in this copy: lib_scratch's state_dir writes CUTIT_INPORT into
# main-dev.pd's u_root box, or 9002 for a gate run by hand.
INPORT = int(os.environ.get("CUTIT_INPORT") or 9002)


def press(n):
    """A Launchpad CC button: its press, and its release 60 ms later."""
    return [(0, "\\; param lp-cc-%d 127" % n), (60, "\\; param lp-cc-%d 0" % n)]


def param(name, v):
    return "\\; param %s %s" % (name, v)


# A roll waits for the song store's sync, as a drag does: asked for here, to read whose it was.
SYNC = (120, "\\; state sync")


def phone(text):
    return "\\; voices-cmd %s" % text


# Left buttons are CC 90 - 10 row, right 99 - 10 row. The table: xport-6 is REC, slider-1 and btn-a-1
# the first group's fader and top button.
SEQ = [
    # The song's load at about 3.5 s says the page and gives it its voices. DSP on: frames need it.
    (4000, "LOADED", ["\\; pd dsp 1"], GAP),
    (4200, "LEFT-2", press(70), GAP),
    (4400, "LEFT-2-AGAIN", press(70), GAP),
    (4600, "LEFT-EMPTY", press(50), GAP),
    (4800, "RIGHT-5", press(49), GAP),
    (5000, "RIGHT-5-AGAIN", press(49), GAP),
    (5200, "AUX", [param("og-aux", 1)], GAP),
    (5400, "AUX-AGAIN", [param("og-aux", 1)], GAP),
    (5600, "SETUP", [param("lp-setup", 127)], GAP),
    (5800, "SETUP-AGAIN", [param("lp-setup", 127)], GAP),
    # Row 5 made a harmony voice from the phone: the second engine's.
    (6000, "METHOD", [phone("voices method 5 harmony"), phone("voices name 5 second chords")], GAP),
    (6200, "TOO-MANY", [phone("voices method 3 harmony"), phone("voices method 3 drums")], GAP),
    # A voice's page, and PLAY.
    (6400, "ON-PAGE", press(70), GAP),
    (6600, "PLAY", ["\\; start bang"], GAP),
    (6800, "PLAY-AGAIN", press(70) + [(100, "\\; start bang")], GAP),
    (7000, "STOP", ["\\; stop bang", "\\; panic bang"], GAP),
    (7200, "BACK-PERFORM", press(70), GAP),
    # Tempo into play. With nothing Saved, knob 1 is held at 120 until turned through it: 0.5 is
    # above, 0.3 through it and 103 BPM.
    (7400, "ARM", [param("xport-6", 1)], GAP),
    (7500, "HEARD", [param("og-knob-1", 0.5), param("og-knob-1", 0.3)], GAP),
    (7700, "BIND", [param("slider-1", 64)], GAP),
    # The song store hears within 300 ms, the surfaces within 40.
    (8100, "BOUND", [], GAP),
    (8300, "MOVE", [param("slider-1", 127)], GAP),
    # Row 2's roll of chords into play, on a button, from its own page; and the same pad on row 5's
    # page, which is the second engine's.
    (8500, "ON-ROW-2", press(70), GAP),
    (8700, "ARM-2", [param("xport-6", 1)], GAP),
    (8800, "HEARD-2", press(102) + [SYNC], GAP),
    (9000, "BIND-2", [param("btn-a-1", 1)], GAP),
    (9200, "ON-ROW-5", press(40), GAP),
    (9400, "ACTIVE-2", press(102) + [SYNC], GAP),
    # From the performance page, the button in play rolls row 2's engine, and it isn't on show.
    (9800, "ON-PERFORM", press(40), GAP),
    (10000, "PLAYED-2", [(0, param("btn-a-1", 1)), SYNC], GAP),
    (10500, "LAMP-2", press(101) + [SYNC], GAP),
    # A new section copies the list: the phone's new, the top row's fourth, stopped: at once.
    (11000, "NEW", [phone("sections new")], GAP),
    (11300, "SECTION-2", press(94), GAP),
    (11600, "HELD", [param("slider-1", 20)], GAP),
    (11800, "CAUGHT", [param("slider-1", 127)], GAP),
    # Tapping a column.
    (12100, "TAP", [param("pad-41", 127), param("pad-41", 0)], GAP),
    (12400, "SECTION-NONE", [], GAP),
    # The draft's timer is every 2 s from the load.
    (14400, "FLUSHED", [], GAP),
]
QUIT_MS = 14800

BLURB = ("voices-assert-drive -- GENERATED by voices-assert-drive-gen.py. Do not edit this file. It "
         "presses the columns \\, aux and Setup \\, sets a voice's method from the phone \\, takes "
         "controls into play and plays them \\, and starts a new section \\, in a copy of the "
         "instrument with no song saved.")

NOTES = [
    "Run it through test/gate/voices-assert.sh: it rewrites the MIDI objects to printing stubs in a "
    "scratch copy. Against the real patch it would send real MIDI.",
    "voices-cmd is a bare name outside the allowlist \\, and safe: it exists only in this driver \\, "
    "in a gate's scratch copy. It carries a command to the socket below \\, which sends it to u_net's "
    "inbound port as the phone would.",
]


def socket(obj, msg, con):
    """/cutit <command> into u_net: gates run under -batch, which polls no socket, so it's the same
    bytes into the same oscparse (lib_scratch.net_direct)."""
    rc = obj(3300, 1300, "r voices-cmd")
    la = obj(3300, 1350, "list append")
    of = obj(3300, 1400, "oscformat cutit")
    lp = obj(3300, 1450, "list prepend send")
    lt = obj(3300, 1500, "list trim")
    ns = obj(3300, 1600, "route send")
    gn = obj(3300, 1650, "s gate-net")
    for a, b in ((rc, la), (la, of), (of, lp), (lp, lt), (lt, ns), (ns, gn)):
        con(a, 0, b, 0)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: voices-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/voices-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="VOICES", taps=["mode", "state", "err", "tempo"],
                      quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES, extra=socket)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
