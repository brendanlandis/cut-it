#!/usr/bin/env python3
"""Generates the timed driver for the Launchpad gate, into the scratch path given.

No DSP: the gate asserts on two SysEx messages and their order, and none of it
needs a clock. The driver does nothing before the panic: boot is the first act,
and the analyser reads its order out of the capture.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20

SEQ = [
    # u_init enters Programmer Mode behind a delay of seconds (ref/module/boot.md);
    # a panic before that would have nothing to undo.
    (2500, "SETTLED", [], GAP),
    (3000, "PANIC", ["\\; panic bang"], GAP),
    # Quitting is the only thing that hands the surface back: this window is
    # the test of the path that keeps a Launchpad from being stranded.
    (3500, "QUIT", ["\\; quitting bang"], GAP),
]
QUIT_MS = 4500

BLURB = ("launchpad-assert-drive -- GENERATED by launchpad-assert-drive-gen.py. Do "
         "not edit this file. It drives m_launchpad's own SysEx: Programmer Mode at "
         "boot \\, a panic that keeps the surface \\, and Live Mode on quit. It "
         "paints nothing and needs no clock.")

NOTES = [
    "Run it through test/gate/launchpad-assert.sh: it reads [t_midiout] in a "
    "scratch copy.",

    "⛔ Live Mode on quit is the one that costs a power cycle: a Launchpad left in "
    "Programmer Mode is stranded \\, and nothing on the Organelle can put it back.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: launchpad-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/launchpad-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="LP",
                      taps=[], quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
