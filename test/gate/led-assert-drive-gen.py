#!/usr/bin/env python3
"""Generates the timed driver for the aux LED gate, into the scratch path given.

It needs only the disp bus. The unknown state comes after a known one, so "the
LED is left alone" is asserted against an LED that was just driven.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 40

SEQ = [
    # Before the boot finishes: g_led needs no table or restore, and u_init is
    # still pushing modal stages onto this bus, which a loose route would take.
    (300, "EARLY", ["\\; disp led running"], GAP),

    (5000, "OFF", ["\\; disp led off"], GAP),
    (5700, "STOPPED", ["\\; disp led stopped"], GAP),
    (6400, "RUNNING", ["\\; disp led running"], GAP),
    (7100, "PANIC", ["\\; disp led panic"], GAP),

    (7800, "UNKNOWN", ["\\; disp led flashing"], GAP),

    # g_led shares disp with g_oled and g_grid, and each sees every message: a
    # parameter row here, as u_map sends one.
    (8500, "NOT-LED", ["\\; disp chop-size 43 %"], GAP),

    (9200, "DONE", [], GAP),
]
QUIT_MS = 9900

BLURB = ("led-assert-drive -- GENERATED by led-assert-drive-gen.py. Do not edit this "
         "file. It drives g_led over the disp bus: the four states and their four "
         "mother values \\, a state it does not recognize \\, and a disp selector "
         "that is not its own.")

NOTES = [
    "Run it through test/gate/led-assert.sh: it taps the led bus \\, mother's own "
    "name \\, which nothing here listens to.",

    "⛔ stopped is 5 \\, lit \\, not 0: a patch that is up but stopped must not "
    "look dead \\, and the OLED goes dark for both.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: led-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/led-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="LED",
                      taps=["led", "err", "disp"], quit_ms=QUIT_MS,
                      blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
