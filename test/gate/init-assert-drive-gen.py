#!/usr/bin/env python3
"""Generates the timed driver for the boot-sequence gate.

It drives nothing: u_init's subject is the boot left alone, so the windows
only divide it into before and after. The assertions are about order, not
milliseconds, since the stage timings are guesses with evidence (item 266).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 40

SEQ = [
    # Before this mark is the loadbang stage, which lib_assert buckets as "PRE":
    # without it, one midiInGate send cannot be told from two.
    (1000, "AFTER-LOADBANG", [], GAP),

    # Before the launchpad stage and the restore.
    (2500, "MID-BOOT", [], GAP),

    # Long after the last stage.
    (5000, "SETTLED", [], GAP),
    (7000, "QUIET", [], GAP),

    (8000, "DONE", [], GAP),
]
QUIT_MS = 8600

BLURB = ("init-assert-drive -- GENERATED by init-assert-drive-gen.py. Do not edit "
         "this file. It drives NOTHING: u_init's subject is what happens without "
         "anybody touching the instrument \\, so these windows only divide the boot "
         "into before and after.")

NOTES = [
    "Run it through test/gate/init-assert.sh \\, which copies a counting stub over "
    "shell.pd (mac-stubs/shell.pd swallows the command) and seeds one known line "
    "into each state file \\, since a restore from empty files publishes nothing.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: init-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/init-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="INIT",
                      taps=["disp", "state", "midiInGate", "midiOutGate"],
                      quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
