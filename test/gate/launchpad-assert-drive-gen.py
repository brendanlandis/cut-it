#!/usr/bin/env python3
"""Generates the timed driver for the Launchpad gate, into the scratch path given.

No DSP: the gate asserts on SysEx and its order, and none of it needs a clock.
The driver does nothing before the panic: boot is the first act, and the
analyser reads its order out of the capture.

It also plays the device's side of one conversation. Entering Programmer Mode
makes the Launchpad announce it on its third port, which wire.sh joins to
Midi-In 1, and a tap on Setup makes the same announcement unasked (the
Launchpad's Reference page, The Setup button in Programmer Mode). So the driver
watches what m_launchpad sends the device, through t_midiout's t-midiout, and
answers every Programmer Mode entry 1 ms later, as the device does within a
millisecond, until a window mutes it. Its answers are the patch's own entries,
whenever they come, never a time read off the implementation (the gate skill).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20

# The Launchpad's output port in Pd, and what it is told and says (Reference).
LP_PORT = 1
ENTER = [240, 0, 32, 41, 2, 14, 14, 1, 247]                    # enter Programmer Mode
ANNOUNCE = [240, 0, 32, 41, 2, 14, 0, 17, 0, 0, 247]            # layout 0x11, Programmer


def frame(data):
    """A SysEx frame arriving from the Launchpad, as a driver message."""
    return "\\; t-sysexin %d %s" % (LP_PORT, " ".join(map(str, data)))


TAP = frame(ANNOUNCE)

SEQ = [
    # u_init enters Programmer Mode behind a delay of seconds (ref/module/boot.md);
    # a panic before that would have nothing to undo.
    (2500, "SETTLED", [], GAP),
    (3000, "PANIC", ["\\; panic bang"], GAP),
    # A pad held across two presence ticks (every 2 s from 4 s): re-entering
    # Programmer Mode makes the device let go of a held pad, so the heartbeat
    # waits while one is down, and comes back once it is let go (Brendan,
    # 2026-11-04: the repeat pads gave up after a second or so).
    # A ring button counts too: it is pressed before the pad is let go, so the
    # tick at 8 s finds only it down.
    (4500, "HELD", ["\\; t-notein 45 100 1"], GAP),
    (6500, "SWAP", ["\\; t-ctlin 127 91 1", "\\; t-notein 45 0 1"], GAP),
    (9000, "LET-GO", ["\\; t-ctlin 0 91 1"], GAP),
    # A tap on Setup: the announcement with no entry before it. Every entry so
    # far was answered, so none is waiting, and it must reach param as lp-setup
    # and, through the map, flip test mode on.
    (10500, "TAP", [TAP], GAP),
    # Frames that are not that announcement, with nothing waiting either: a
    # Live Mode layout's (02, seen on port 3 in Live Mode), and the announcement
    # a byte short and a byte long. None is a tap.
    (10800, "OTHER", [frame(ANNOUNCE[:7] + [2] + ANNOUNCE[8:]),
                      frame(ANNOUNCE[:-2] + [247]),
                      frame(ANNOUNCE[:-1] + [0, 247])], GAP),
    # The device stops answering, and the next entry's echo never comes. A tap
    # well after it must still be a tap: an echo that was never sent is
    # forgotten rather than waiting to swallow the next tap. It flips test mode
    # back off.
    (11000, "MUTE", ["\\; t-lp-echo 0"], GAP),
    (12600, "LOST", [TAP], GAP),
    # Quitting is the only thing that hands the surface back: this window is
    # the test of the path that keeps a Launchpad from being stranded.
    (13000, "QUIT", ["\\; quitting bang"], GAP),
]
QUIT_MS = 14000

BLURB = ("launchpad-assert-drive -- GENERATED by launchpad-assert-drive-gen.py. Do "
         "not edit this file. It drives m_launchpad's own SysEx: Programmer Mode at "
         "boot \\, a panic that keeps the surface \\, and Live Mode on quit. It "
         "paints nothing and needs no clock. A pad held holds the Programmer Mode "
         "heartbeat off. The boxes on the right are the device: each Programmer Mode "
         "entry is answered with the announcement \\, until t-lp-echo 0.")

NOTES = [
    "Run it through test/gate/launchpad-assert.sh: it reads [t_midiout] in a "
    "scratch copy.",

    "⛔ Live Mode on quit is the one that costs a power cycle: a Launchpad left in "
    "Programmer Mode is stranded \\, and nothing on the Organelle can put it back.",
]


def device(first, x=3000):
    """The Launchpad's answer to an entry: (records, connects) for boxes numbered
    from `first`, the driver's box count.

    t_midiout sends `byte port` on t-midiout. The match is m_launchpad's own
    three rules, for ENTER: F0 resets the index and sets the match, every byte
    must equal ENTER's at its index or the match clears, and F7 bangs a match
    still standing. Then [del 1], a print the analyzer counts, and the frame.
    """
    B, C = [], []

    def box(kind, y, text, dx=0):
        B.append("#X %s %d %d %s;" % (kind, x + dx, y, text))
        return first + len(B) - 1

    def cord(a, ao, b, bi):
        C.append("#X connect %d %d %d %d;" % (a, ao, b, bi))

    rx = box("obj", 100, "r t-midiout")
    unp = box("obj", 150, "unpack f f")
    port = box("obj", 200, "== %d" % LP_PORT, 120)
    gate = box("obj", 250, "spigot")
    rt = box("obj", 300, "moses 248")
    tri = box("obj", 350, "t f f f")
    f0 = box("obj", 400, "select 240", 600)
    f0t = box("obj", 450, "t b b", 600)
    zero_i = box("msg", 500, "0", 600)
    one_ok = box("msg", 500, "1", 700)
    tbf = box("obj", 400, "t b f", 250)
    idx = box("obj", 450, "f", 250)
    tff = box("obj", 500, "t f f", 250)
    inc = box("obj", 500, "+ 1", 340)
    get = box("msg", 550, "get \\$1 1", 250)
    want = box("obj", 600, "list store " + " ".join(map(str, ENTER)), 250)
    ne = box("obj", 660, "!=", 600)
    miss = box("obj", 710, "select 1", 600)
    clr = box("msg", 760, "0", 450)
    f7 = box("obj", 400, "select 247")
    f7t = box("obj", 450, "t b b")
    ok = box("obj", 800, "f")
    hit = box("obj", 850, "select 1")
    mute = box("obj", 900, "spigot 1")
    rmute = box("obj", 850, "r t-lp-echo", 120)
    late = box("obj", 950, "del 1")
    say = box("obj", 1000, "t b b")
    pr = box("obj", 1050, "print LPECHO", 120)
    ans = box("msg", 1050, TAP)

    cord(rx, 0, unp, 0)
    cord(unp, 1, port, 0)
    cord(port, 0, gate, 1)
    cord(unp, 0, gate, 0)
    cord(gate, 0, rt, 0)
    cord(rt, 0, tri, 0)
    cord(tri, 2, f0, 0)
    cord(f0, 0, f0t, 0)
    cord(f0t, 1, zero_i, 0)
    cord(f0t, 0, one_ok, 0)
    cord(zero_i, 0, idx, 1)
    cord(one_ok, 0, ok, 1)
    cord(tri, 1, tbf, 0)
    cord(tbf, 1, ne, 1)
    cord(tbf, 0, idx, 0)
    cord(idx, 0, tff, 0)
    cord(tff, 1, inc, 0)
    cord(inc, 0, idx, 1)
    cord(tff, 0, get, 0)
    cord(get, 0, want, 0)
    cord(want, 0, ne, 0)
    cord(want, 1, clr, 0)
    cord(ne, 0, miss, 0)
    cord(miss, 0, clr, 0)
    cord(clr, 0, ok, 1)
    cord(tri, 0, f7, 0)
    cord(f7, 0, f7t, 0)
    cord(f7t, 1, ok, 0)
    cord(f7t, 0, clr, 0)
    cord(ok, 0, hit, 0)
    cord(hit, 0, mute, 0)
    cord(rmute, 0, mute, 1)
    cord(mute, 0, late, 0)
    cord(late, 0, say, 0)
    cord(say, 1, pr, 0)
    cord(say, 0, ans, 0)
    return B, C


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: launchpad-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/launchpad-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="LP",
                      taps=["param", "err"], quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES)
    # The device's boxes go after everything build wrote: a box is numbered by
    # its place among the boxes, so the connects after them still name the right ones.
    boxes, cords = device(b)
    with open(sys.argv[1], "a") as fh:
        fh.write("\n".join(boxes + cords) + "\n")
    print("%s  %d windows  %d boxes  %d connects"
          % (sys.argv[1], w, b + len(boxes), c + len(cords)))
