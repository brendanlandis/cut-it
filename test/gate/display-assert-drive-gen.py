#!/usr/bin/env python3
"""Generates the timed driver for the display gate, into the scratch path given.

It presses the left and right columns, aux and Setup as the Launchpad and the Organelle publish them,
and pushes onto disp, err, tempo, start and panic as a controller would.

DSP is off for the first windows: with no clock the grid has nothing to redraw,
so `idle-dsp-off` proves the dirty flag gates the repaint. Everything after it
needs DSP, because the clock's beats are what repaint an idle page.

The state directory holds a page from the last power-off, row 1's left page (scratch-gates.py). Only
that says what the first painted frame should be: it's restored before the frame clock runs, and
before the song that holds row 1's voice.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20



def press(n):
    """A Launchpad CC button: its press, and its release, 60 ms later."""
    return [(0, "\\; param lp-cc-%d 127" % n), (60, "\\; param lp-cc-%d 0" % n)]


# The seeded song: row 1 the drums, row 2 harmony, row 3 melody (u_voices.lua's seed).
SEQ = [
    (4000, "idle-dsp-off", [], GAP),
    (8000, "dsp-on", ["\\; pd dsp 1"], GAP),
    (8600, "settling", ["\\; tempo 120"], GAP),
    # The page isn't re-sent: the next window asserts the one saved survived.
    (11000, "home-restored", [], GAP),
    (14000, "harmony", press(70), GAP),
    (14500, "harmony-again", press(70), GAP),
    (15000, "melody", press(60), GAP),
    (15500, "sound", press(69), GAP),
    (16000, "new-voice", press(49), GAP),
    (16500, "aux", ["\\; param og-aux 1"], GAP),
    (17000, "aux-again", ["\\; param og-aux 1"], GAP),
    (17500, "setup", ["\\; param lp-setup 127"], GAP),
    (18000, "setup-again", ["\\; param lp-setup 127"], GAP),
    # The drum page is under the layers that follow.
    (19000, "drums", press(80), GAP),
    (20000, "modal-45", ["\\; disp grid modal 45"], GAP),
    # u_err draws a warn on every page, so it reaches disp here: the grid must
    # ignore it, since it draws fails alone.
    (23000, "warn-ignored", ["\\; err warn u_bench quiet"], GAP),
    (26000, "alert-red", ["\\; err fail u_bench boom"], GAP),
    # the alert TTL is 2 s, so this window opens after it has expired
    (28500, "alert-expired", [], GAP),
    (31000, "home-again", ["\\; disp grid modal-off"], GAP),
    # PLAY brings up the performance page by itself.
    (34000, "play", ["\\; start bang"], GAP),
    (41000, "after-panic", ["\\; panic bang"], GAP),
    (45000, "done", [], GAP),
]
QUIT_MS = 46000

BLURB = ("display-assert-drive -- GENERATED by display-assert-drive-gen.py. Do not "
         "edit this file. It drives the display arbiter: the dirty flag \\, the home "
         "layer \\, its pages and the voices' lamps \\, a modal claiming the whole "
         "surface \\, an alert outranking it and expiring back to it \\, and the "
         "surface still painting after a panic.")

NOTES = [
    "Run it through test/gate/display-assert.sh: it reads [t_midiout] in a scratch "
    "copy \\, and against the real Cut It every assertion passes vacuously.",

    "It needs DSP: an idle page repaints on the beats c_clock cuts with threshold~. "
    "-noaudio leaves DSP running (item 280).",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: display-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/display-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="GRID",
                      taps=[], quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
