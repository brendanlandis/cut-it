#!/usr/bin/env python3
"""Generates the timed driver for the tempo gate, into the scratch path given.

The windows are measurements: the analyser counts System Real-Time bytes over
a known span, so moving or shortening one changes the number it is checked
against.

The rate windows start at 4000 ms, after u_init restores saved state at about
3.5 s: a counting window straddling the restore could have its tempo changed
mid-count. The clamp and transport windows assert on events and are unaffected.

DSP goes on at 300 ms and stays on: the pulse is BPM / 60 * 24 into a [phasor~],
then [threshold~ 0.5 0 0.1 0] for one bang per cycle. -noaudio leaves DSP
running (item 280).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20

# BPM / 60 * 24 Hz is 48 Hz at 120 BPM, so a two-second window holds 96 pulses
# per port.
SEQ = [
    (300, "DSP-ON", ["\\; pd dsp 1"], GAP),

    (4000, "RATE-120", [], GAP),                 # 4000..6000, 2 s at 120 BPM
    (6000, "SET-60", ["\\; tempo 60"], GAP),
    (6200, "RATE-60", [], GAP),                  # 6200..8200, 2 s at 60 BPM
    (8200, "SET-120", ["\\; tempo 120"], GAP),

    # An in-range tempo must not warn. [change] sits on the value, not the
    # verdict: filtering the flag would make a 500 warn and a following 5 silent.
    (8400, "IN-RANGE", [], GAP),
    # 5000 is clamped to 600 BPM, 240 Hz; unclamped it saturates at ~338.
    (9000, "TOO-HIGH", ["\\; tempo 5000"], GAP),
    (10000, "TOO-LOW", ["\\; tempo 0"], GAP),
    (11000, "BACK", ["\\; tempo 120"], GAP),

    (12000, "START", ["\\; start bang"], GAP),
    (13000, "STOP", ["\\; stop bang"], GAP),
    # Stop does not halt the clock: halting is the consumer's business.
    (13500, "AFTER-STOP", [], GAP),
    (15000, "PANIC", ["\\; panic bang"], GAP),
]
QUIT_MS = 16000

BLURB = ("tempo-assert-drive -- GENERATED by tempo-assert-drive-gen.py. Do not edit "
         "this file. It drives u_tempo: the pulse rate at two tempos \\, the clamp at "
         "both ends and its warning \\, the three transport bytes \\, and the fact that "
         "a stop does not halt the clock.")

NOTES = [
    "Run it through test/gate/tempo-assert.sh: it reads [t_midiout] in a scratch "
    "copy.",

    "It needs DSP: u_tempo's pulse is a [phasor~] read by [threshold~]. -noaudio "
    "leaves DSP running (item 280).",

    "The clock goes out on port 1 alone \\, for the Launchpad's animations: port 3 "
    "was the SP-404's \\, and the set of ports it reaches is asserted exactly.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: tempo-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/tempo-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="CLK",
                      taps=["err"], quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
