#!/usr/bin/env python3
"""Generates the timed driver for the device-presence gate, into the scratch path.

The stimulus is a silence: [sysexin] is rewritten to [t_sysexin] and no reply is
pushed until 17000, so the Launchpad is absent at load (item 235). The analyzer's
liveness witnesses are what keep that silence from passing a copy that never
loaded. The two active layers go lost together on one tick, so every count is
a claim about the shared bound.

The schedule is u_present's own arithmetic:

    4000 ms   the settle expires; [metro 2000] fires at once, so ticks are
              4000, 6000, 8000, ...
    8000 ms   the third missed tick: both active sources go lost, and the
              recovery counter starts in the same tick (the tick is broadcast
              before the recovery step reads the gate)
   14000 ms   counter 4: the first wire.sh fork
   17000 ms   a KORG reply: m_nano is seen, armed, and publishes back
   22000 ms   counter 8: the second fork, since m_launchpad has not answered.
              m_nano is lost again, armed this time, so its warn reaches err
   24000 ms   a Novation reply: m_launchpad is seen and armed
   30000 ms   counter 12: the third fork, since m_nano is still lost.
              m_launchpad is lost again, armed, so ownership drops
   33000 ms   both devices answer, beside a Roland reply nobody may take (the
              SP-404's, which left the rig): the trailing fork

The windows straddle 8000 and 14000 rather than sitting after them, so "fires
on the fourth tick" can be told from "fires on every tick". The give-up is
presence-bound-drive-gen.py's, in a second run at a tenth of the clock.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 40

SEQ = [
    # u_init's wire.sh at 1500 ms lands here: the liveness witness.
    (300, "BOOT", [], GAP),

    # Before the third missed poll. Nothing has been declared lost yet.
    (6000, "BEFORE-LOSS", [], GAP),

    # Empty: ticks 1 and 2 of the recovery counter. A re-wire here means the
    # interval is gone, and eight attempts over 70 s become thirty-four.
    (9000, "AFTER-LOSS", [], GAP),

    # The fourth recovery tick lands at 14000, inside this window.
    (13000, "WAITING", [], GAP),

    # A mode change dirties g_grid, which paints only while it owns the surface:
    # a frame here proves a detector that never saw a reply didn't drop it.
    (15000, "AFTER-REWIRE", ["\\; mode mode-3"], GAP),

    # Cross-talk: a KORG reply (byte 66, item 249) on the [sysexin] every layer
    # reads. Only m_nano may take it.
    (17000, "FOREIGN",
     ["\\; t-sysexin 2 240 126 0 6 2 66 4 1 0 0 35 0 0 0 247"], GAP),

    # The second re-wire is due at 22000.
    (21000, "STILL-LOST", [], GAP),

    # The positive control, since a c_devid that matches nothing passes the
    # window above: the Launchpad's own reply, byte 0 (item 98).
    (24000, "OWN-REPLY",
     ["\\; t-sysexin 1 240 126 0 6 2 0 32 41 35 1 0 0 0 4 6 5 247"], GAP),

    # Coalescing: the Launchpad is back, but m_nano went quiet again, so the
    # shared counter is not reset and the third re-wire lands at 30000, in
    # here. One recovery per lost source would show more.
    (28000, "RECOVERED", [], GAP),

    # The arming gate opens: the Launchpad answered at 24000 and is lost again
    # at 30000, so ownership drops and this mode change must not paint.
    (31000, "DROPPED", ["\\; mode mode-1"], GAP),

    # Both devices answer at once, the only way to a lost count of zero, which
    # fires the trailing fork (item 275). Counter 16 is not due until 38000, so
    # a fork here can only be the trailing one. The third frame is a Roland
    # reply (byte 65), the SP-404's: it left the rig on 2026-11-04, and no
    # layer may take it.
    (33000, "ALL-BACK",
     ["\\; t-sysexin 1 240 126 0 6 2 0 32 41 35 1 0 0 0 4 6 5 247",
      "\\; t-sysexin 2 240 126 0 6 2 66 4 1 0 0 35 0 0 0 247",
      "\\; t-sysexin 3 240 126 16 6 2 65 8 4 0 0 0 3 0 0 247"], GAP),

    # The phone's button, where nothing on the schedule is due. Not inside
    # SETTLED, which asserts zero forks; not after it, since past 38000 the two
    # devices miss their third poll again and `device-lost` lands in windows
    # that must be quiet (tried at 38000: four checks went red).
    (34500, "PHONE-REWIRE", ["\\; presence re-wire"], GAP),

    (36000, "SETTLED", [], GAP),
]
QUIT_MS = 38000

BLURB = ("presence-assert-drive -- GENERATED by presence-assert-drive-gen.py. Do not "
         "edit this file. It withholds every device inquiry reply (item 235) and "
         "hands them back late. The re-wire must still fire on the fourth tick \\, "
         "one bound must serve two lost sources \\, and the grid stays owned until "
         "a device that has been seen goes away.")

NOTES = [
    "Run it through test/gate/presence-assert.sh: against the real Cut It no fork "
    "prints and every count is answered by an empty list.",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: presence-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/presence-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="PRES", taps=["err", "presence"],
                      quit_ms=QUIT_MS, blurb=BLURB, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
