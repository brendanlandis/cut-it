#!/usr/bin/env python3
"""Generates the timed driver for the SP-404 gate, into the scratch path it is given.

m_404's receive side sits behind [notein], which no bus reaches, so the gate
rewrites it to t_notein and this driver sends bare `t-notein <pitch> <velocity>
<channel>`. t-notein is outside the allowlist on purpose: it exists only in the
scratch copy.

Both directions are exercised before u_map reads its table (item 234).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_drive as D                                          # noqa: E402

GAP = 20

SEQ = [
    # Before u_map reads its table, both ways round.
    (300, "EARLY-TX", ["\\; param gk-p1 100"], GAP),
    # 700, not 400: the pad above sends its note-off 200 ms behind its note-on.
    (700, "EARLY-RX", ["\\; t-notein 48 77 33"], GAP),
    # Spaced well clear of the 5 ms limiter, and the next window leaves room for
    # the last note-off, 200 ms behind.
    (2900, "PADS-A", ["\\; param gk-p%d 100" % n for n in range(1, 17)], GAP),
    (3600, "PADS-C", ["\\; param gk-pc1 100"], GAP),
    (4000, "RX-B5", ["\\; t-notein 44 90 34"], GAP),
    (4100, "RX-RELEASE", ["\\; t-notein 44 0 34"], GAP),
    (4200, "RX-A1", ["\\; t-notein 48 77 33"], GAP),
    (4300, "RX-REJECT", ["\\; t-notein 44 90 20"], GAP),
    # Two triggers 2 ms apart straddle the 5 ms gate: the only window that sees
    # a disarmed limiter, since the burst is one logical instant ([del 0] adds no
    # logical time).
    (4800, "PAIR", ["\\; param gk-p1 100", "\\; param gk-p2 100"], 2),
    (5400, "PANIC", ["\\; panic bang"], GAP),
]
BURST = (4600, 20, "\\; param gk-p1 100")
QUIT_MS = 6000

BLURB = ("sp404-assert-drive -- GENERATED by sp404-assert-drive-gen.py. Do not edit "
         "this file. It drives m_404 in BOTH directions: all sixteen pads of bank A \\, "
         "a second bank \\, the rate limiter from two sides \\, four incoming pad events "
         "including one on a channel the 404 does not own \\, and panic.")

NOTES = [
    "Run it through test/gate/sp404-assert.sh: it rewrites noteout \\, ctlout and "
    "notein to printing stubs in a scratch copy and appends its own map rows. "
    "Against the real patch it would send real MIDI.",

    "The state directory is the gate's own and empty: a mode restored from /tmp at "
    "about 3.5 s would break every row keyed to another mode (item 232).",
]

if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: sp404-assert-drive-gen.py OUT.pd  "
                 "(run it through test/gate/sp404-assert.sh, which passes a scratch path)")
    w, b, c = D.build(sys.argv[1], SEQ, tag="SP404",
                      taps=["param", "disp", "err"], quit_ms=QUIT_MS,
                      blurb=BLURB, burst=BURST, notes=NOTES)
    print("%s  %d windows  %d boxes  %d connects" % (sys.argv[1], w, b, c))
